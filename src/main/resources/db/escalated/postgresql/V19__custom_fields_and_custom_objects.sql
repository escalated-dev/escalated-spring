-- PostgreSQL edition of db/escalated/mysql/V19__custom_fields_and_custom_objects.sql.
-- The two are one migration: change them together, never one alone.

-- Custom fields take the rest of escalated-laravel's columns. The existing
-- ones keep their names (field_key is the slug, field_type the type,
-- is_required, sort_order the position, is_active), so no data moves.
ALTER TABLE escalated_custom_fields ADD COLUMN context VARCHAR(255) NOT NULL DEFAULT 'ticket';
ALTER TABLE escalated_custom_fields ADD COLUMN placeholder VARCHAR(255) NULL;
ALTER TABLE escalated_custom_fields ADD COLUMN validation_rules TEXT NULL;
ALTER TABLE escalated_custom_fields ADD COLUMN conditions TEXT NULL;

-- One value per field per ticket. Older installs could store the same pair
-- twice; the newest row is the one kept.
DELETE FROM escalated_custom_field_values older
    USING escalated_custom_field_values newer
    WHERE older.ticket_id = newer.ticket_id
      AND older.custom_field_id = newer.custom_field_id
      AND older.id < newer.id;
ALTER TABLE escalated_custom_field_values
    ADD CONSTRAINT uq_escalated_cfv_ticket_field UNIQUE (ticket_id, custom_field_id);

-- Custom objects: admin-defined record types with a JSON field schema.
CREATE TABLE escalated_custom_objects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(100) NOT NULL,
    fields_schema TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_escalated_custom_objects_slug UNIQUE (slug)
);

CREATE TABLE escalated_custom_object_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id BIGINT NOT NULL,
    data TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (object_id) REFERENCES escalated_custom_objects(id) ON DELETE CASCADE
);

CREATE INDEX idx_escalated_custom_object_records_object ON escalated_custom_object_records (object_id);
