-- Custom ticket statuses (escalated-laravel's escalated_ticket_statuses, plus
-- is_system).
--
-- A custom status is a sub-status of one of five categories: new, open,
-- pending, on_hold, solved. A ticket given one keeps the category's built-in
-- anchor in escalated_tickets.status, which stays the source of truth for the
-- lifecycle, and points at the custom status with ticket_status_id. Existing
-- tickets have none (NULL) and behave exactly as before.
--
-- One system row per built-in status, slug = the built-in value lower-cased.
-- Their slug and category never change and they cannot be deleted.

CREATE TABLE escalated_ticket_statuses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL,
    category VARCHAR(20) NOT NULL,
    color VARCHAR(20) NOT NULL DEFAULT '#6b7280',
    description TEXT NULL,
    position INT NOT NULL DEFAULT 0,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    is_system BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_escalated_ticket_statuses_slug UNIQUE (slug)
);

CREATE INDEX idx_escalated_ticket_statuses_category ON escalated_ticket_statuses (category, position);

